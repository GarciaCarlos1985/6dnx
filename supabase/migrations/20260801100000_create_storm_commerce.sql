-- 6DNX real PIX commerce foundation.
-- IMPORTANT: review in an isolated Supabase branch before applying.
-- Existing catalog prices are imported as DRAFT and cannot create charges.

create extension if not exists pgcrypto;

create table if not exists public.commerce_offers (
  id uuid primary key default gen_random_uuid(),
  product_source_key text not null
    references public.product_catalog(source_key) on delete restrict,
  variant_name text not null check (char_length(variant_name) between 1 and 120),
  amount_cents integer not null check (amount_cents between 1 and 10000000),
  currency text not null default 'BRL' check (currency = 'BRL'),
  status text not null default 'draft'
    check (status in ('draft', 'approved', 'suspended')),
  approval_note text check (char_length(approval_note) <= 240),
  approved_at timestamptz,
  approved_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_source_key, variant_name),
  check (
    status <> 'approved'
    or (approved_at is not null and approval_note is not null)
  )
);

create index if not exists commerce_offers_status_idx
  on public.commerce_offers (status, product_source_key);

create table if not exists public.commerce_orders (
  id uuid primary key,
  client_request_id uuid not null unique,
  external_id text not null unique
    check (char_length(external_id) between 1 and 100),
  offer_id uuid not null
    references public.commerce_offers(id) on delete restrict,
  product_source_key text not null,
  product_slug text not null check (char_length(product_slug) between 1 and 96),
  product_title text not null check (char_length(product_title) between 1 and 100),
  variant_name text not null check (char_length(variant_name) between 1 and 120),
  amount_cents integer not null check (amount_cents between 1 and 10000000),
  currency text not null default 'BRL' check (currency = 'BRL'),
  payer_name text not null check (char_length(payer_name) between 3 and 100),
  payer_document_hash text not null
    check (payer_document_hash ~ '^[a-f0-9]{64}$'),
  payer_document_last4 text not null
    check (payer_document_last4 ~ '^[0-9]{4}$'),
  request_fingerprint_hash text not null
    check (request_fingerprint_hash ~ '^[a-f0-9]{64}$'),
  status text not null default 'pending_payment'
    check (
      status in (
        'pending_payment',
        'payment_creation_failed',
        'paid',
        'failed',
        'cancelled'
      )
    ),
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists commerce_orders_fingerprint_created_idx
  on public.commerce_orders (request_fingerprint_hash, created_at desc);
create index if not exists commerce_orders_status_created_idx
  on public.commerce_orders (status, created_at desc);

create table if not exists public.commerce_payment_attempts (
  order_id uuid primary key
    references public.commerce_orders(id) on delete cascade,
  provider text not null default 'storm_wallet'
    check (provider = 'storm_wallet'),
  provider_payment_id text check (
    provider_payment_id is null
    or char_length(provider_payment_id) between 1 and 160
  ),
  idempotency_key text check (
    idempotency_key is null
    or char_length(idempotency_key) between 1 and 100
  ),
  provider_status text check (
    provider_status is null
    or provider_status in ('PENDENTE', 'COMPLETO', 'FALHA')
  ),
  provider_complete_observed_at timestamptz,
  last_polled_at timestamptz,
  last_error_code text check (
    last_error_code is null or char_length(last_error_code) <= 80
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists commerce_attempts_provider_payment_unique
  on public.commerce_payment_attempts (provider_payment_id)
  where provider_payment_id is not null;
create unique index if not exists commerce_attempts_idempotency_unique
  on public.commerce_payment_attempts (idempotency_key)
  where idempotency_key is not null;

create table if not exists public.commerce_webhook_events (
  id bigint generated by default as identity primary key,
  event_key text not null unique check (event_key ~ '^[a-f0-9]{64}$'),
  order_id uuid not null
    references public.commerce_orders(id) on delete cascade,
  event_name text not null
    check (event_name in ('payment.completed', 'payment.failed')),
  provider_payment_id text not null
    check (char_length(provider_payment_id) between 1 and 160),
  external_id text not null check (char_length(external_id) between 1 and 100),
  amount_cents integer not null check (amount_cents between 1 and 10000000),
  provider_status text not null check (provider_status in ('COMPLETO', 'FALHA')),
  processed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (provider_payment_id, event_name)
);

create index if not exists commerce_webhook_events_order_idx
  on public.commerce_webhook_events (order_id, created_at desc);

create or replace function public.touch_commerce_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := clock_timestamp();
  return new;
end;
$$;

revoke all on function public.touch_commerce_updated_at()
  from public, anon, authenticated;

