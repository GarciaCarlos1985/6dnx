-- Copy the current catalog into the commercial review queue. Nothing below is
-- approved automatically, even when a reference price exists in the catalog.
insert into public.commerce_offers (
  product_source_key,
  variant_name,
  amount_cents,
  status
)
select
  catalog.source_key,
  variant.value ->> 'name',
  round(((variant.value ->> 'priceBRL')::numeric) * 100)::integer,
  'draft'
from public.product_catalog as catalog
cross join lateral jsonb_array_elements(catalog.variants) as variant(value)
where
  nullif(variant.value ->> 'name', '') is not null
  and (variant.value ->> 'priceBRL') ~ '^[0-9]+([.][0-9]{1,2})?$'
  and ((variant.value ->> 'priceBRL')::numeric) > 0
on conflict (product_source_key, variant_name) do nothing;
