drop policy if exists "Published catalog is publicly readable"
  on public.product_catalog;
create policy "Published catalog is publicly readable"
on public.product_catalog
for select
to anon, authenticated
using (
  publication_state = 'published'
  or public.is_catalog_admin()
);

drop policy if exists "Admins can insert catalog products"
  on public.product_catalog;
create policy "Admins can insert catalog products"
on public.product_catalog
for insert
to authenticated
with check (public.is_catalog_admin());

drop policy if exists "Admins can update catalog products"
  on public.product_catalog;
create policy "Admins can update catalog products"
on public.product_catalog
for update
to authenticated
using (public.is_catalog_admin())
with check (public.is_catalog_admin());

drop policy if exists "Admins can read catalog history"
  on public.product_catalog_revisions;
create policy "Admins can read catalog history"
on public.product_catalog_revisions
for select
to authenticated
using (public.is_catalog_admin());

